def svh():
    """The same table as a SystemVerilog localparam, 256 entries."""
    out = ["// Written by tools/scancodes.py -- do not edit.",
           "// The 8042's set 2 -> set 1 scancode table. 00 means a code with",
           "// no set 1 equivalent, which the caller drops.",
           "localparam logic [7:0] XT [0:255] = '{"]
    for i in range(0, 256, 8):
        row = ", ".join("8'h%02X" % SET2_TO_SET1.get(i + j, 0) for j in range(8))
        out.append("    " + row + ("," if i < 248 else "") + "   // %02X" % i)
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    import os
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "..", "rom", "scancodes.svh")
    with open(path, "w") as f:
        f.write(svh())
    print("wrote rom/scancodes.svh (%d mappings)" % len(SET2_TO_SET1))
