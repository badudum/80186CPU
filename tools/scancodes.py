#!/usr/bin/env python3
"""The 8042's set 2 -> set 1 scancode table, and nothing else.

ONE TABLE, TWO CONSUMERS, WHICH IS THE WHOLE POINT OF THIS FILE.
modules/keyboard_controller.sv translates the bytes arriving from the PS/2
port, and tools/gen_bios.py builds the BIOS's scancode-to-ASCII table for
whatever the keyboard controller hands it. If those two ever disagree about
what a key is, the machine types the wrong characters -- and that is a hard
bug to see, because it looks like a broken keyboard rather than two tables
that drifted apart. So the hardware table is GENERATED from this file, into
rom/scancodes.svh, rather than written out twice:

    python3 tools/scancodes.py

WHY TRANSLATE AT ALL. PS/2 keyboards power up in set 2; PC software expects
set 1. A real PC's 8042 converts between them, and DOS games read port 60h
directly rather than going through the BIOS, so the conversion has to happen
in hardware or it does not happen for them at all. See the header of
modules/keyboard_controller.sv for what goes wrong without it.

Codes with no set 1 equivalent are absent, and both consumers treat a missing
entry as "drop this byte" rather than inventing a code for it.
"""

